"""Full per-case pipeline: sequence the generate, train, and compare stages."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from neuralls.application.models import AssignmentResult
from neuralls.composition.assignments.assembler import load_validated_case_config
from neuralls.composition.assignments.comparison_batch import run_comparison_batch
from neuralls.composition.assignments.comparison_report import run_comparison_report
from neuralls.composition.assignments.training_batch import run_assignment_sweep
from neuralls.composition.comparison.models import (
    ComparisonCompleted,
    ComparisonOutcome,
    ComparisonParams,
    ComparisonReused,
)
from neuralls.composition.generation.multi_generation import generate_batch
from neuralls.composition.tracking.services import MLFLOW_TRACKING, TrackingServices
from neuralls.platform.config.settings import NeurallsSettings, require_settings
from neuralls.shared.device import release_device_memory


@dataclass(frozen=True, slots=True)
class ForcePolicy:
    """Which pipeline stages ignore an existing matching result and rerun.

    Attributes:
        generate: Regenerate every dataset.
        train: Retrain every assignment.
        compare: Rerun every comparison.
        expand: Recreate sweep-generated dataset configs.
    """

    generate: bool = False
    train: bool = False
    compare: bool = False
    expand: bool = False

    @classmethod
    def resolve(
        cls, *, everything: bool, generate: bool, train: bool, compare: bool, expand: bool
    ) -> ForcePolicy:
        """Combine the blanket flag with the per-stage flags: a stage reruns if either says so."""
        return cls(
            generate=everything or generate,
            train=everything or train,
            compare=everything or compare,
            expand=everything or expand,
        )


NO_FORCE = ForcePolicy()


def run_case_pipeline(
    case_config_path: Path,
    settings: NeurallsSettings | None = None,
    *,
    force: ForcePolicy = NO_FORCE,
    tracking: TrackingServices = MLFLOW_TRACKING,
) -> tuple[list[AssignmentResult], list[ComparisonOutcome]]:
    """Run the full pipeline for one case config: generate, train, then compare.

    Sequences the exact same three stage functions `neuralls generate`/`train`/
    `compare` call directly — `generate_batch()`, `run_assignment_sweep()`, and
    `run_comparison_batch()` — adding no stage logic of its own. Each stage
    keeps its own independent reuse check, so a dataset regenerated by stage 1
    automatically cascades into retraining (stage 2, via its dataset-hash
    reuse check) and recomparing (stage 3, via its checkpoint-dependency reuse
    check) exactly the affected assignments/comparisons, without invoking
    three separate commands by hand. Training and comparisons are each
    skipped entirely when the case config declares no `[[comparisons]]` or
    `[[comparison_sweeps]]` — a case config may
    legitimately declare only `[[comparisons]]` with preconditioners inline
    in `comparison_baseline` (e.g. POD-2G weighting variants that need the
    matrix at fit time, which a checkpoint-backed `fit` job can't provide).

    Args:
        case_config_path: Path to a case config defining datasets, assignments,
            and (optionally) comparisons.
        settings: Optional pre-loaded runtime settings.
        force: Which stages ignore an existing matching result and rerun.
        tracking: Source of the MLflow clients, lease managers and reuse lookups.

    Returns:
        Tuple of (assignment results, comparison outcomes). Each list is
        empty when the case config declares no `[[assignments]]` /
        `[[comparisons]]` respectively.
    """
    settings = require_settings(settings, case_config_path=case_config_path)
    cfg, config_dir = load_validated_case_config(
        case_config_path, settings, force_expand=force.expand
    )

    generate_batch(cfg, config_dir, settings, force=force.generate)

    assignment_results: list[AssignmentResult] = []
    if cfg.assignments:
        sweep_result = run_assignment_sweep(
            case_config_path,
            settings=settings,
            force=force.train,
            tracking=tracking,
        )
        assignment_results = sweep_result.results

    if not cfg.comparisons and not cfg.comparison_sweeps:
        return assignment_results, []

    # Training and comparison run in this same process with no allocator
    # reset between them — a CUDA-heavy training sweep otherwise leaves the
    # caching allocator holding blocks that starve even the cheapest
    # comparison (e.g. the unpreconditioned baseline).
    release_device_memory()

    comparison_outcomes = run_comparison_batch(
        case_config_path,
        ComparisonParams(force=force.compare),
        settings=settings,
        tracking=tracking,
    )
    if any(isinstance(o, (ComparisonCompleted, ComparisonReused)) for o in comparison_outcomes):
        run_comparison_report(case_config_path, settings=settings, tracking=tracking)
    return assignment_results, comparison_outcomes
